"""Nonconvex stochastic-FRAMES adaptation of the QPT_BFW experiment.

The decision variable remains QPT_BFW's Burer--Monteiro factor ``U`` with
``chi = U U^H`` and ``||U||_op <= tau``.  Thus the measurement objective is
nonconvex.  Trace preservation is represented by the indicator of ``I_d``
after the nonlinear map

    A(U) = sum_nm (U U^H)_nm A_m^H A_n.

At the user's request, the FRAMES linear-composite update is applied to this
map using its current-point Jacobian adjoint.  The active smoothing schedule
therefore controls ``||A(U) - I_d||_F^2 / (2 beta_k)``, while the momentum
estimator sees only a uniformly sampled measurement-loss gradient.

The HDF5 loader consumes the files generated by QPT_BFW's
``qutomo_gt_gen.ipynb``.  Running from an existing file requires NumPy and
h5py, but not JAX or Qiskit.  Qiskit remains necessary to generate that file
or to compute its exact process-fidelity metric.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
from time import perf_counter
from typing import Callable, Optional, Union

import numpy as np

from frank_wolfe import ObjectiveFunction, StochasticFrames


Schedule = Optional[Union[float, Callable[[int], float]]]


def _hermitian_part(matrix):
    matrix = np.asarray(matrix)
    return 0.5 * (matrix + matrix.conj().T)


@dataclass
class QPTData:
    """Arrays used by the QPT_BFW tomography experiment."""

    f_vector: np.ndarray
    D_tensors: np.ndarray
    A_basis: np.ndarray
    chi_star: Optional[np.ndarray] = None
    B_tensors: Optional[np.ndarray] = None

    def __post_init__(self):
        f_vector = np.asarray(self.f_vector)
        if f_vector.ndim != 1:
            raise ValueError("f_vector must have shape (m,).")
        if f_vector.size == 0:
            raise ValueError("f_vector must contain at least one measurement.")
        if np.iscomplexobj(f_vector):
            imaginary_scale = np.max(np.abs(f_vector.imag))
            if imaginary_scale > 1e-10:
                raise ValueError("f_vector must be real-valued.")
            f_vector = f_vector.real
        f_vector = np.asarray(f_vector, dtype=float)

        D_tensors = np.asarray(self.D_tensors, dtype=np.complex128)
        A_basis = np.asarray(self.A_basis, dtype=np.complex128)
        if D_tensors.ndim != 3 or D_tensors.shape[1] != D_tensors.shape[2]:
            raise ValueError("D_tensors must have shape (m, d^2, d^2).")
        if D_tensors.shape[0] != f_vector.shape[0]:
            raise ValueError(
                "D_tensors and f_vector must contain the same number of "
                "measurements."
            )
        if A_basis.ndim != 3 or A_basis.shape[1] != A_basis.shape[2]:
            raise ValueError("A_basis must have shape (d^2, d, d).")

        process_dimension = D_tensors.shape[1]
        d = A_basis.shape[1]
        if process_dimension != d**2 or A_basis.shape[0] != d**2:
            raise ValueError(
                "The process dimension and Pauli basis are inconsistent: "
                "expected D_tensors.shape[1] == A_basis.shape[0] == d^2."
            )

        if not np.all(np.isfinite(f_vector)):
            raise ValueError("f_vector must contain finite values.")
        if not np.all(np.isfinite(D_tensors)):
            raise ValueError("D_tensors must contain finite values.")
        if not np.all(np.isfinite(A_basis)):
            raise ValueError("A_basis must contain finite values.")

        if self.B_tensors is None:
            # B[n, m] = A[m]^H A[n], matching QPT_BFW's generated tensor.
            B_tensors = np.einsum(
                "mki,nkj->nmij",
                A_basis.conj(),
                A_basis,
                optimize=True,
            )
        else:
            B_tensors = np.asarray(self.B_tensors, dtype=np.complex128)
        expected_B_shape = (d**2, d**2, d, d)
        if B_tensors.shape != expected_B_shape:
            raise ValueError(
                f"B_tensors must have shape {expected_B_shape}; got "
                f"{B_tensors.shape}."
            )
        if not np.all(np.isfinite(B_tensors)):
            raise ValueError("B_tensors must contain finite values.")

        chi_star = self.chi_star
        if chi_star is not None:
            chi_star = np.asarray(chi_star, dtype=np.complex128)
            expected_chi_shape = (d**2, d**2)
            if chi_star.shape != expected_chi_shape:
                raise ValueError(
                    f"chi_star must have shape {expected_chi_shape}; got "
                    f"{chi_star.shape}."
                )
            if not np.all(np.isfinite(chi_star)):
                raise ValueError("chi_star must contain finite values.")

        self.f_vector = f_vector
        self.D_tensors = D_tensors
        self.A_basis = A_basis
        self.B_tensors = B_tensors
        self.chi_star = chi_star

    @property
    def m(self):
        return self.f_vector.shape[0]

    @property
    def d(self):
        return self.A_basis.shape[1]

    @property
    def process_dimension(self):
        return self.d**2

    @classmethod
    def from_hdf5(cls, path):
        """Load a file produced by QPT_BFW's data-generation notebook."""

        try:
            import h5py
        except ImportError as error:
            raise ImportError(
                "Loading QPT_BFW data requires h5py. Install the 'qpt' "
                "optional dependencies with `pip install -e '.[qpt]'`."
            ) from error

        with h5py.File(path, "r") as handle:
            required = (
                "f_jax_vector",
                "D_jax_tensors",
                "A_jax_basis",
            )
            missing = [key for key in required if key not in handle]
            if missing:
                raise KeyError(
                    "Missing required QPT dataset(s): " + ", ".join(missing)
                )
            chi_star = (
                np.asarray(handle["Chi_star_tensor"])
                if "Chi_star_tensor" in handle
                else None
            )
            B_tensors = (
                np.asarray(handle["B_jax_tensors"])
                if "B_jax_tensors" in handle
                else None
            )
            return cls(
                f_vector=np.asarray(handle["f_jax_vector"]),
                D_tensors=np.asarray(handle["D_jax_tensors"]),
                A_basis=np.asarray(handle["A_jax_basis"]),
                chi_star=chi_star,
                B_tensors=B_tensors,
            )


def pack_factor(matrix):
    """Pack a complex Burer--Monteiro factor into real coordinates."""

    matrix = np.asarray(matrix)
    return np.concatenate([matrix.real.ravel(), matrix.imag.ravel()])


def unpack_factor(vector, process_dimension, rank):
    """Unpack real coordinates into a complex factor."""

    vector = np.asarray(vector, dtype=float)
    expected_size = 2 * process_dimension * rank
    if vector.ndim != 1 or vector.size != expected_size:
        raise ValueError(
            f"the packed factor must have shape ({expected_size},); got "
            f"{vector.shape}."
        )
    half = expected_size // 2
    return vector[:half].reshape(process_dimension, rank) + 1j * vector[
        half:
    ].reshape(process_dimension, rank)


class QPTMeasurementObjective(ObjectiveFunction):
    """Nonconvex factorized measurement loss with a minibatch oracle.

    ``linear_operator`` deliberately supplies the nonlinear trace-preserving
    map ``A(U) = T(U U^H)`` to FRAMES.  ``linear_operator_adjoint_at`` returns
    the adjoint of its Jacobian at the current factor, which is the requested
    point-dependent analogue of the adjoint used for a linear composite map.
    """

    def __init__(self, data, rank=1, batch_size=1, seed=None):
        super().__init__()
        if not isinstance(rank, (int, np.integer)) or rank <= 0:
            raise ValueError("rank must be a positive integer.")
        if not isinstance(batch_size, (int, np.integer)) or batch_size <= 0:
            raise ValueError("batch_size must be a positive integer.")
        self.data = data
        self.rank = int(rank)
        self.batch_size = int(batch_size)
        self.rng = np.random.default_rng(seed)
        self.last_batch_indices = None
        self.sampled_measurements = 0

    def unpack(self, vector):
        return unpack_factor(vector, self.data.process_dimension, self.rank)

    def process_matrix(self, vector):
        factor = self.unpack(vector)
        return factor @ factor.conj().T

    def sensing_values(self, vector, indices=None):
        chi = self.process_matrix(vector)
        tensors = (
            self.data.D_tensors
            if indices is None
            else self.data.D_tensors[np.asarray(indices)]
        )
        values = np.einsum(
            "mab,ab->m", tensors.conj(), chi, optimize=True
        )
        return values.real

    @staticmethod
    def _validate_indices(indices, measurement_count):
        indices = np.asarray(indices)
        if indices.ndim != 1 or indices.size == 0:
            raise ValueError("indices must be a nonempty one-dimensional array.")
        if not np.issubdtype(indices.dtype, np.integer):
            raise TypeError("measurement indices must be integers.")
        indices = indices.astype(int, copy=False)
        if np.any(indices < 0) or np.any(indices >= measurement_count):
            raise IndexError("measurement index is out of range.")
        return indices

    def gradient_for_indices(self, vector, indices):
        """Return an unbiased packed-real measurement gradient."""

        factor = self.unpack(vector)
        indices = self._validate_indices(indices, self.data.m)
        sensing = self.sensing_values(vector, indices=indices)
        residual = sensing - self.data.f_vector[indices]
        chi_gradient = np.einsum(
            "m,mab->ab",
            residual,
            self.data.D_tensors[indices],
            optimize=True,
        ) / indices.size
        chi_gradient = _hermitian_part(chi_gradient)
        return 2.0 * pack_factor(chi_gradient @ factor)

    def loss_and_gradient(self, vector):
        sensing = self.sensing_values(vector)
        residual = sensing - self.data.f_vector
        loss = 0.5 * np.mean(residual**2)
        gradient = self.gradient_for_indices(vector, np.arange(self.data.m))
        return float(loss), gradient

    def evaluate(self, vector):
        return self.loss_and_gradient(vector)[0]

    def gradient(self, vector):
        return self.loss_and_gradient(vector)[1]

    def stochastic_gradient(self, vector):
        indices = self.rng.integers(0, self.data.m, size=self.batch_size)
        self.last_batch_indices = indices.copy()
        self.sampled_measurements += self.batch_size
        return self.gradient_for_indices(vector, indices)

    def linear_operator(self, vector):
        chi = self.process_matrix(vector)
        return np.einsum(
            "nm,nmij->ij", chi, self.data.B_tensors, optimize=True
        )

    def linear_operator_adjoint_at(self, vector, matrix):
        matrix = np.asarray(matrix, dtype=np.complex128)
        expected = (self.data.d, self.data.d)
        if matrix.shape != expected:
            raise ValueError(
                f"the trace-preserving residual must have shape {expected}; "
                f"got {matrix.shape}."
            )
        factor = self.unpack(vector)
        chi_gradient = np.einsum(
            "nmij,ij->nm",
            self.data.B_tensors.conj(),
            matrix,
            optimize=True,
        )
        chi_gradient = _hermitian_part(chi_gradient)
        return 2.0 * pack_factor(chi_gradient @ factor)

    def trace_preserving_residual(self, vector):
        return self.linear_operator(vector) - np.eye(
            self.data.d, dtype=np.complex128
        )


def create_trace_preserving_prox(d):
    """Create ``prox_{beta indicator_{I_d}}``, which is constant at ``I_d``."""

    identity = np.eye(d, dtype=np.complex128)

    def prox(matrix, beta):
        del matrix, beta
        return identity.copy()

    return prox


def create_operator_norm_factor_lmo(process_dimension, rank, tau):
    """Exact LMO for the complex operator-norm ball in real coordinates."""

    if not np.isfinite(tau) or tau <= 0:
        raise ValueError("tau must be a positive finite number.")

    def lmo(packed_gradient):
        gradient = unpack_factor(packed_gradient, process_dimension, rank)
        if np.linalg.norm(gradient, ord="fro") == 0:
            return np.zeros_like(packed_gradient, dtype=float)
        left, _, right_h = np.linalg.svd(gradient, full_matrices=False)
        return pack_factor(-tau * (left @ right_h))

    return lmo


def make_factor_initial_point(data, rank=1, seed=0):
    """Match QPT_BFW's trace-normalized random complex initialization."""

    if not isinstance(rank, (int, np.integer)) or rank <= 0:
        raise ValueError("rank must be a positive integer.")
    rng = np.random.default_rng(seed)
    factor = rng.uniform(0.0, 1.0, (data.process_dimension, rank))
    factor = factor + 1j * rng.uniform(
        0.0, 1.0, (data.process_dimension, rank)
    )
    factor *= np.sqrt(data.d) / np.linalg.norm(factor, ord="fro")
    return pack_factor(factor)


def process_fidelity_proxy(chi, chi_star, d):
    """JAX/Qiskit-free overlap proxy used by QPT_BFW for quick traces."""

    if chi_star is None:
        return np.nan
    trace = np.trace(chi).real
    if not np.isfinite(trace) or trace <= 0:
        return np.nan
    normalized = chi * (d / trace)
    return float(np.vdot(chi_star, normalized).real / d**2)


@dataclass(frozen=True)
class PowerSchedule:
    """Power-law schedule ``min(cap, scale / (k + offset)^exponent)``."""

    scale: float
    offset: float
    exponent: float
    cap: Optional[float] = None

    def __post_init__(self):
        values = (self.scale, self.offset, self.exponent)
        if not all(np.isfinite(value) for value in values):
            raise ValueError("power schedule parameters must be finite.")
        if self.scale <= 0 or self.offset <= 0 or self.exponent < 0:
            raise ValueError(
                "a power schedule requires scale > 0, offset > 0, and "
                "exponent >= 0."
            )
        if self.cap is not None and (
            not np.isfinite(self.cap) or self.cap <= 0
        ):
            raise ValueError("power schedule cap must be positive and finite.")

    def __call__(self, iteration):
        value = self.scale / (iteration + self.offset) ** self.exponent
        return value if self.cap is None else min(self.cap, value)


def checkpoint_iterations(n_steps, frequency):
    """Return checkpoint indices, always including the initial and final point."""

    if not isinstance(n_steps, (int, np.integer)) or n_steps < 0:
        raise ValueError("n_steps must be a nonnegative integer.")
    if not isinstance(frequency, (int, np.integer)) or frequency < 0:
        raise ValueError("metrics_frequency must be a nonnegative integer.")
    if n_steps == 0:
        return np.array([0], dtype=int)
    if frequency == 0:
        return np.array([0, n_steps], dtype=int)
    steps = list(range(0, n_steps + 1, int(frequency)))
    if steps[-1] != n_steps:
        steps.append(n_steps)
    return np.asarray(steps, dtype=int)


class _CheckpointRecorder:
    def __init__(self, n_steps, frequency):
        self.requested_steps = set(
            checkpoint_iterations(n_steps, frequency).tolist()
        )
        self.steps = []
        self.times = []
        self.iterates = []
        self.started_at = None

    def start(self):
        self.started_at = perf_counter()

    def __call__(self, completed_steps, vector):
        if completed_steps not in self.requested_steps:
            return
        if self.started_at is None:
            raise RuntimeError("the checkpoint recorder clock was not started.")
        now = perf_counter()
        self.steps.append(completed_steps)
        self.times.append(
            0.0
            if completed_steps == 0
            else now - self.started_at
        )
        # StochasticFrames already provides an owned defensive copy.
        self.iterates.append(np.asarray(vector))


@dataclass
class QPTExperimentResult:
    """Optimization trace with full metrics evaluated only at checkpoints."""

    rank: int
    tau: float
    final_x: np.ndarray
    final_factor: np.ndarray
    final_chi: np.ndarray
    checkpoint_steps: np.ndarray
    optimizer_seconds: np.ndarray
    measurement_loss: np.ndarray
    tp_violation: np.ndarray
    smoothed_objective: np.ndarray
    process_fidelity_proxy: np.ndarray
    exact_smoothed_gap: np.ndarray
    minimum_eigenvalue: np.ndarray
    checkpoint_smoothing_parameters: np.ndarray
    estimated_gaps: np.ndarray
    momentum_weights: np.ndarray
    smoothing_parameters: np.ndarray
    step_sizes: np.ndarray
    cumulative_stochastic_oracles: np.ndarray
    cumulative_sampled_measurements: np.ndarray
    algorithm: StochasticFrames


def _checkpoint_smoothing_parameters(steps, smoothing_parameters):
    """Align beta_k with x_k, using the last applied beta at terminal x_T."""

    if len(smoothing_parameters) == 0:
        return np.full(len(steps), np.nan)
    indices = np.minimum(steps, len(smoothing_parameters) - 1)
    return smoothing_parameters[indices]


def run_qpt_stochastic_frames(
    data,
    *,
    n_steps=1000,
    rank=1,
    tau=10.0,
    batch_size=1,
    initialization_seed=0,
    sampling_seed=0,
    x0=None,
    beta0=10.0,
    rho_schedule: Schedule = None,
    smoothing_schedule: Schedule = None,
    step_size_schedule: Schedule = None,
    metrics_frequency=100,
    show_progress=True,
):
    """Run nonconvex stochastic FRAMES on QPT_BFW's factor ``U``.

    Custom schedules are forwarded unchanged to :class:`StochasticFrames`.
    A scalar makes a schedule constant; a callable receives the zero-based
    iteration and returns the actual value used at that iteration.  Interior
    checkpoint ``x_k`` is diagnosed with ``beta_k``; since the optimizer never
    requests ``beta_T``, terminal ``x_T`` uses the last applied value
    ``beta_{T-1}``.  Checkpoint metrics are computed after the timed run.  The
    reported optimizer time includes the sparse defensive checkpoint copies,
    but excludes the full post-hoc measurement passes.
    """

    if not isinstance(n_steps, (int, np.integer)) or n_steps <= 0:
        raise ValueError("n_steps must be a positive integer.")
    expected_checkpoints = checkpoint_iterations(n_steps, metrics_frequency)
    objective = QPTMeasurementObjective(
        data, rank=rank, batch_size=batch_size, seed=sampling_seed
    )
    lmo = create_operator_norm_factor_lmo(
        data.process_dimension, objective.rank, tau
    )
    prox = create_trace_preserving_prox(data.d)

    if x0 is None:
        x0 = make_factor_initial_point(
            data, rank=objective.rank, seed=initialization_seed
        )
    x0 = np.asarray(x0, dtype=float)
    if not np.all(np.isfinite(x0)):
        raise ValueError("x0 must contain finite values.")
    factor0 = objective.unpack(x0)
    if np.linalg.norm(factor0, ord=2) > tau + 1e-10:
        raise ValueError("x0 must satisfy the operator-norm constraint.")

    recorder = _CheckpointRecorder(n_steps, metrics_frequency)
    algorithm = StochasticFrames(
        objective,
        lmo,
        prox,
        objective_type="indicator",
    )
    recorder.start()
    algorithm.run(
        x0,
        beta0=beta0,
        n_steps=n_steps,
        show_progress=show_progress,
        rho_schedule=rho_schedule,
        smoothing_schedule=smoothing_schedule,
        step_size_schedule=step_size_schedule,
        evaluate_objective=False,
        iterate_callback=recorder,
        iterate_callback_frequency=metrics_frequency,
    )

    checkpoint_steps = np.asarray(recorder.steps, dtype=int)
    if not np.array_equal(checkpoint_steps, expected_checkpoints):
        raise RuntimeError("the optimizer did not emit the expected checkpoints.")
    checkpoint_beta = _checkpoint_smoothing_parameters(
        checkpoint_steps, algorithm.smoothing_parameters
    )

    measurement_loss = []
    tp_violation = []
    smoothed_objective = []
    fidelity_proxy = []
    exact_smoothed_gap = []
    minimum_eigenvalue = []
    identity = np.eye(data.d, dtype=np.complex128)

    for vector, beta in zip(recorder.iterates, checkpoint_beta):
        loss, smooth_gradient = objective.loss_and_gradient(vector)
        tp_residual = objective.linear_operator(vector) - identity
        violation = np.linalg.norm(tp_residual, ord="fro")
        moreau_gradient = (
            objective.linear_operator_adjoint_at(vector, tp_residual) / beta
        )
        combined_gradient = smooth_gradient + moreau_gradient
        atom = lmo(combined_gradient)
        chi = objective.process_matrix(vector)

        measurement_loss.append(loss)
        tp_violation.append(violation)
        smoothed_objective.append(loss + 0.5 * violation**2 / beta)
        fidelity_proxy.append(
            process_fidelity_proxy(chi, data.chi_star, data.d)
        )
        exact_smoothed_gap.append(
            np.dot(combined_gradient, vector - atom)
        )
        minimum_eigenvalue.append(
            np.linalg.eigvalsh(_hermitian_part(chi))[0]
        )

    sampled_measurements = np.rint(
        batch_size * algorithm.num_stochastic_oracles
    ).astype(int)
    final_factor = objective.unpack(algorithm.x)
    return QPTExperimentResult(
        rank=objective.rank,
        tau=float(tau),
        final_x=algorithm.x.copy(),
        final_factor=final_factor,
        final_chi=final_factor @ final_factor.conj().T,
        checkpoint_steps=checkpoint_steps,
        optimizer_seconds=np.asarray(recorder.times),
        measurement_loss=np.asarray(measurement_loss),
        tp_violation=np.asarray(tp_violation),
        smoothed_objective=np.asarray(smoothed_objective),
        process_fidelity_proxy=np.asarray(fidelity_proxy),
        exact_smoothed_gap=np.asarray(exact_smoothed_gap),
        minimum_eigenvalue=np.asarray(minimum_eigenvalue),
        checkpoint_smoothing_parameters=checkpoint_beta.copy(),
        estimated_gaps=algorithm.estimated_gaps.copy(),
        momentum_weights=algorithm.momentum_weights.copy(),
        smoothing_parameters=algorithm.smoothing_parameters.copy(),
        step_sizes=algorithm.step_sizes.copy(),
        cumulative_stochastic_oracles=(
            algorithm.num_stochastic_oracles.copy()
        ),
        cumulative_sampled_measurements=sampled_measurements.copy(),
        algorithm=algorithm,
    )


def save_qpt_result(path, result, metadata=None):
    """Save a result in a NumPy archive without pickled Python objects."""

    payload = {
        "meta_formulation": np.asarray(
            "nonconvex_factor_nonlinear_tp_smoothing"
        ),
        "meta_nonlinear_composite": np.asarray(
            "jacobian_adjoint_as_linear"
        ),
        "meta_rank": np.asarray(result.rank),
        "meta_tau": np.asarray(result.tau),
        "final_x": result.final_x,
        "final_factor": result.final_factor,
        "final_chi": result.final_chi,
        "checkpoint_steps": result.checkpoint_steps,
        "optimizer_seconds": result.optimizer_seconds,
        "measurement_loss": result.measurement_loss,
        "tp_violation": result.tp_violation,
        "smoothed_objective": result.smoothed_objective,
        "process_fidelity_proxy": result.process_fidelity_proxy,
        "exact_smoothed_gap": result.exact_smoothed_gap,
        "minimum_eigenvalue": result.minimum_eigenvalue,
        "checkpoint_smoothing_parameters": (
            result.checkpoint_smoothing_parameters
        ),
        "estimated_gaps": result.estimated_gaps,
        "momentum_weights": result.momentum_weights,
        "smoothing_parameters": result.smoothing_parameters,
        "step_sizes": result.step_sizes,
        "cumulative_stochastic_oracles": (
            result.cumulative_stochastic_oracles
        ),
        "cumulative_sampled_measurements": (
            result.cumulative_sampled_measurements
        ),
    }
    if metadata:
        payload.update(
            {f"meta_{key}": np.asarray(value) for key, value in metadata.items()}
        )
    np.savez_compressed(path, **payload)


def plot_qpt_result(result, path=None):
    """Plot checkpoint metrics against completed stochastic iterations."""

    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    steps = result.checkpoint_steps
    fig, axes = plt.subplots(2, 2, figsize=(13, 9))
    axes[0, 0].semilogy(steps, np.maximum(result.measurement_loss, 1e-30))
    axes[0, 0].set_title("Measurement loss")
    axes[0, 1].semilogy(steps, np.maximum(result.tp_violation, 1e-30))
    axes[0, 1].set_title("Trace-preserving violation")
    axes[1, 0].semilogy(steps, np.maximum(result.exact_smoothed_gap, 1e-30))
    axes[1, 0].set_title("Exact smoothed FW gap")
    if np.isfinite(result.process_fidelity_proxy).any():
        axes[1, 1].plot(steps, result.process_fidelity_proxy)
        axes[1, 1].set_title("Process-fidelity proxy")
    else:
        axes[1, 1].axis("off")
    for axis in axes.flat:
        if axis.axison:
            axis.set_xlabel("Completed stochastic iterations")
            axis.grid(True, alpha=0.3)
    fig.tight_layout()
    if path is not None:
        fig.savefig(path, dpi=150, bbox_inches="tight")
    return fig


def _build_parser():
    parser = argparse.ArgumentParser(
        description=(
            "Run nonconvex stochastic FRAMES on QPT_BFW's factorized "
            "QPT problem with scheduled trace-preservation smoothing."
        )
    )
    parser.add_argument(
        "--h5",
        type=Path,
        required=True,
        help="HDF5 file generated by QPT_BFW/qutomo_gt_gen.ipynb.",
    )
    parser.add_argument("--steps", type=int, default=10_000)
    parser.add_argument(
        "--rank", type=int, default=1, help="Burer--Monteiro factor rank."
    )
    parser.add_argument(
        "--tau", type=float, default=10.0, help="Operator-norm ball radius."
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=1,
        help=(
            "Number of measurements sampled uniformly with replacement per "
            "gradient oracle."
        ),
    )
    parser.add_argument(
        "--metrics-every",
        type=int,
        default=100,
        help="Full-metric checkpoint interval; zero records endpoints only.",
    )
    parser.add_argument("--initialization-seed", type=int, default=0)
    parser.add_argument("--sampling-seed", type=int, default=0)

    schedules = parser.add_argument_group(
        "power schedules",
        "Each schedule is scale / (iteration + offset)^exponent. "
        "Rho and step size are capped at one. rho_0 is recorded, but the "
        "first gradient sample initializes d_0 without scaling.",
    )
    schedules.add_argument("--rho-scale", type=float, default=4.0)
    schedules.add_argument("--rho-offset", type=float, default=8.0)
    schedules.add_argument(
        "--rho-exponent", type=float, default=2.0 / 3.0
    )
    schedules.add_argument(
        "--smoothing-scale",
        type=float,
        default=10.0,
        help=(
            "Smoothing beta scale for the nonlinear trace-preserving map. "
            "Ten gives initial Moreau weight 0.05, matching QPT_BFW's fixed "
            "penalty weight."
        ),
    )
    schedules.add_argument("--smoothing-offset", type=float, default=1.0)
    schedules.add_argument(
        "--smoothing-exponent", type=float, default=0.25
    )
    schedules.add_argument("--step-scale", type=float, default=1.0)
    schedules.add_argument("--step-offset", type=float, default=1.0)
    schedules.add_argument("--step-exponent", type=float, default=0.5)

    parser.add_argument("--save", type=Path, default=None)
    parser.add_argument("--plot", type=Path, default=None)
    parser.add_argument("--quiet", action="store_true")
    return parser


def main(argv=None):
    args = _build_parser().parse_args(argv)
    data = QPTData.from_hdf5(args.h5)
    rho_schedule = PowerSchedule(
        args.rho_scale,
        args.rho_offset,
        args.rho_exponent,
        cap=1.0,
    )
    smoothing_schedule = PowerSchedule(
        args.smoothing_scale,
        args.smoothing_offset,
        args.smoothing_exponent,
    )
    step_size_schedule = PowerSchedule(
        args.step_scale,
        args.step_offset,
        args.step_exponent,
        cap=1.0,
    )

    print(
        f"Loaded QPT data: d={data.d}, process dimension="
        f"{data.process_dimension}, measurements={data.m}"
    )
    result = run_qpt_stochastic_frames(
        data,
        n_steps=args.steps,
        rank=args.rank,
        tau=args.tau,
        batch_size=args.batch_size,
        initialization_seed=args.initialization_seed,
        sampling_seed=args.sampling_seed,
        rho_schedule=rho_schedule,
        smoothing_schedule=smoothing_schedule,
        step_size_schedule=step_size_schedule,
        metrics_frequency=args.metrics_every,
        show_progress=not args.quiet,
    )
    print(
        f"Final measurement loss={result.measurement_loss[-1]:.6e}, "
        f"TP violation={result.tp_violation[-1]:.6e}, "
        f"exact smoothed gap={result.exact_smoothed_gap[-1]:.6e}"
    )
    if np.isfinite(result.process_fidelity_proxy[-1]):
        print(
            "Final process-fidelity proxy="
            f"{result.process_fidelity_proxy[-1]:.6f}"
        )
    print(
        "Sampled measurements: "
        f"{int(result.cumulative_sampled_measurements[-1])}"
    )

    if args.save is not None:
        save_qpt_result(
            args.save,
            result,
            metadata={
                "formulation": "nonconvex_factor_nonlinear_tp_smoothing",
                "nonlinear_composite": "jacobian_adjoint_as_linear",
                "source_h5": str(args.h5.resolve()),
                "steps": args.steps,
                "rank": args.rank,
                "tau": args.tau,
                "batch_size": args.batch_size,
                "metrics_every": args.metrics_every,
                "initialization_seed": args.initialization_seed,
                "sampling_seed": args.sampling_seed,
                "d": data.d,
                "measurements": data.m,
                "rho_scale": args.rho_scale,
                "rho_offset": args.rho_offset,
                "rho_exponent": args.rho_exponent,
                "smoothing_scale": args.smoothing_scale,
                "smoothing_offset": args.smoothing_offset,
                "smoothing_exponent": args.smoothing_exponent,
                "step_scale": args.step_scale,
                "step_offset": args.step_offset,
                "step_exponent": args.step_exponent,
            },
        )
        print(f"Saved results to {args.save}")
    if args.plot is not None:
        plot_qpt_result(result, args.plot)
        print(f"Saved plot to {args.plot}")

    return result


if __name__ == "__main__":
    main()
